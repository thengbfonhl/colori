import { ARTWORKS, artworksIn, categoryIcon, getArtwork, getArtworkAssets } from '../data/catalog';
import { CATEGORIES, CATEGORY_IDS } from '../data/categories';
import { en } from '../i18n/en';
import { vi } from '../i18n/vi';

describe('artwork catalog (generated by npm run art:build)', () => {
  it('has artworks with unique ids in manifest order', () => {
    expect(ARTWORKS.length).toBeGreaterThan(0);
    expect(new Set(ARTWORKS.map((a) => a.id)).size).toBe(ARTWORKS.length);
    expect(ARTWORKS.map((a) => a.order)).toEqual(ARTWORKS.map((_, i) => i + 1));
  });

  it('every artwork has its three images and valid metadata', () => {
    for (const a of ARTWORKS) {
      const assets = getArtworkAssets(a.id);
      expect(assets).toBeDefined();
      expect(assets?.line).toBeDefined();
      expect(assets?.regions).toBeDefined();
      expect(assets?.thumb).toBeDefined();
      expect(CATEGORY_IDS).toContain(a.category);
      expect(['easy', 'medium']).toContain(a.level);
      expect(a.audience).toBe('kids');
      expect(a.regionCount).toBeGreaterThan(0);
      expect(a.title.vi.trim()).not.toBe('');
      expect(a.title.en.trim()).not.toBe('');
    }
  });

  it('looks artworks up by id and category', () => {
    const first = ARTWORKS[0];
    expect(getArtwork(first.id)).toBe(first);
    expect(getArtwork('nope')).toBeUndefined();
    expect(artworksIn(first.category)).toContain(first);
    expect(artworksIn(first.category, first.level).every((a) => a.level === first.level)).toBe(true);
  });

  it('picks an easy picture as category icon when there is one', () => {
    for (const c of CATEGORY_IDS) {
      const icon = categoryIcon(c);
      const all = artworksIn(c);
      if (all.length === 0) expect(icon).toBeNull();
      else if (all.some((a) => a.level === 'easy')) expect(icon?.level).toBe('easy');
      else expect(icon).toBe(all[0]);
    }
  });
});

describe('categories', () => {
  it('lists every category id once, with a translated title', () => {
    expect(CATEGORIES.map((c) => c.id)).toEqual([...CATEGORY_IDS]);
    for (const c of CATEGORIES) {
      expect(vi[c.title]).toBeTruthy();
      expect(en[c.title]).toBeTruthy();
    }
  });
});
